import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";

const version = process.argv[2];
if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(version ?? "")) {
  throw new Error("Usage: node scripts/vendor-plot.mjs <exact Plot version>");
}
const esbuildVersion = "0.25.12";
const temp = mkdtempSync(join(tmpdir(), "vendor-plot-"));
const vendor = new URL("../public/vendor/", import.meta.url);
try {
  writeFileSync(join(temp, "package.json"), '{"private":true}\n');
  execFileSync("npm", [
    "install", "--ignore-scripts", "--no-audit", "--no-fund", "--package-lock=false",
    `@observablehq/plot@${version}`, `esbuild@${esbuildVersion}`,
  ], { cwd: temp, stdio: "inherit" });
  writeFileSync(join(temp, "entry.mjs"), 'export * from "@observablehq/plot";\n');
  const { build } = await import(pathToFileURL(join(temp, "node_modules/esbuild/lib/main.js")));
  const result = await build({
    absWorkingDir: temp,
    entryPoints: ["entry.mjs"],
    bundle: true,
    format: "esm",
    minify: true,
    legalComments: "none",
    banner: { js: `// Plot ${version}; generated by scripts/vendor-plot.mjs with esbuild ${esbuildVersion}. See LICENSE.plot.` },
    write: false,
  });

  // Include the full dependency tree: some packages already inline dependencies
  // in their published ESM, so esbuild's input list alone would miss licenses.
  const packages = new Set();
  function collectLicenses(entry) {
    let dir = dirname(entry);
    while (!readdirSync(dir).includes("package.json")) dir = dirname(dir);
    if (packages.has(dir)) return;
    packages.add(dir);
    const manifest = join(dir, "package.json");
    const pkg = JSON.parse(readFileSync(manifest, "utf8"));
    const require = createRequire(manifest);
    for (const dependency of Object.keys(pkg.dependencies ?? {})) {
      collectLicenses(require.resolve(dependency));
    }
  }
  collectLicenses(createRequire(join(temp, "entry.mjs")).resolve("@observablehq/plot"));
  const licenses = [...packages].sort().map((dir) => {
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const files = readdirSync(dir).filter((file) => /^(licen[sc]e|notice)([.-]|$)/i.test(file)).sort();
    if (!pkg.license || !files.some((file) => /^licen[sc]e/i.test(file))) {
      throw new Error(`Missing license for ${pkg.name}`);
    }
    console.log(`${pkg.name}@${pkg.version}: ${pkg.license}`);
    return `${pkg.name}@${pkg.version} (${pkg.license})\n${"=".repeat(72)}\n\n` +
      files.map((file) => readFileSync(join(dir, file), "utf8").trim()).join("\n\n");
  });
  writeFileSync(new URL("LICENSE.plot", vendor), licenses.join("\n\n\n") + "\n");
  writeFileSync(new URL(`plot-${version}.mjs`, vendor), result.outputFiles[0].contents);
  console.log(`Wrote plot-${version}.mjs (${result.outputFiles[0].contents.length} bytes) and LICENSE.plot`);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
